impl SyntaxKind {
    pub fn is_trivia(self) -> bool {
        matches!(
            self,
            Self::Whitespace | Self::LineComment | Self::BlockComment
        )
    }
    pub fn is_assignment(self) -> bool {
        matches!(
            self,
            Self::Eq
                | Self::PlusEq
                | Self::MinusEq
                | Self::StarEq
                | Self::SlashEq
                | Self::PercentEq
                | Self::AmpEq
                | Self::PipeEq
                | Self::CaretEq
                | Self::ShlEq
                | Self::ShrEq
        )
    }
    pub(crate) fn raw(self) -> rowan::SyntaxKind {
        rowan::SyntaxKind(self as u16)
    }
}
